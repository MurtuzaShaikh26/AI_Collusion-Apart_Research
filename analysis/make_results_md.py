"""Build results/RESULTS.md from files under results/. Do not hand-edit that file."""

from __future__ import annotations

import json
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[1]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from collusion_replay.io_utils import now_ist


def _load_dir(folder: Path) -> list[dict]:
    if not folder.exists():
        return []
    rows = []
    for path in sorted(folder.glob("*.json")):
        rows.append(json.loads(path.read_text(encoding="utf-8")))
    return rows


def _cell(value) -> str:
    if value is None:
        return ""
    if isinstance(value, float):
        return f"{value:.6g}"
    if isinstance(value, list):
        return ", ".join(_cell(item) for item in value)
    return str(value)


def _table(headers: list[str], rows: list[dict]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(_cell(row.get(header)) for header in headers) + " |")
    return "\n".join(lines)


def _flatten_signal(row: dict) -> dict:
    inner = row.get("signals") if isinstance(row.get("signals"), dict) else {}
    flat = dict(inner)
    for key, value in row.items():
        if key not in {"signals", "strata"}:
            flat[key] = value
    return flat


def _is_complete(row: dict) -> bool:
    if "complete" in row:
        return bool(row["complete"])
    return row.get("rounds_completed") == row.get("rounds") and bool(row.get("rounds"))


def render(results_root: Path) -> str:
    results_root = Path(results_root)
    summaries = _load_dir(results_root / "summaries")
    signals = [_flatten_signal(row) for row in _load_dir(results_root / "signals")]
    benchmarks = _load_dir(results_root / "benchmarks")
    for row in benchmarks:
        if row.get("seconds_per_call") is None and row.get("n"):
            row["seconds_per_call"] = float(row["elapsed_s"]) / float(row["n"])
    spend_path = results_root / "spend.json"
    spend = json.loads(spend_path.read_text(encoding="utf-8")) if spend_path.exists() else None
    checks = [row for row in summaries if row.get("pipeline_check") or row.get("case") == "SMOKE" or row.get("provider") == "mock"]
    finished = [row for row in summaries if row not in checks and _is_complete(row)]
    incomplete = [row for row in summaries if row not in checks and row not in finished]
    parts = [
        "# RESULTS",
        "",
        "Generated by `analysis/make_results_md.py`. Do not edit by hand.",
        f"Generated at (IST): {now_ist()}",
        "",
        "Rows with provider `mock` or case `SMOKE` are pipeline checks. They are not experimental findings.",
        "",
    ]
    if spend is not None:
        parts.append("## Spend ledger")
        parts.append("")
        parts.append(f"Source: `{spend_path.as_posix()}`")
        parts.append("")
        parts.append(_table(["cumulative_usd", "calls", "prompt_tokens", "completion_tokens", "updated"], [spend]))
        parts.append("")
    parts.append("## Game summaries (scientific)")
    parts.append("")
    if not finished:
        parts.append("No completed scientific run summaries yet.")
    else:
        parts.append(
            _table(
                ["run_id", "case", "seed", "model", "provider", "rounds_completed", "mean_gain_last10", "positive_control", "finished"],
                finished,
            )
        )
    parts.append("")
    parts.append("## Incomplete runs")
    parts.append("")
    parts.append("A stopped run is not a gate result, even if the rounds so far have a high gain.")
    parts.append("")
    if not incomplete:
        parts.append("No incomplete runs.")
    else:
        parts.append(
            _table(
                ["run_id", "case", "seed", "model", "provider", "rounds_completed", "rounds", "mean_gain_last10", "finished"],
                incomplete,
            )
        )
    parts.append("")
    parts.append("## Pipeline checks")
    parts.append("")
    if not checks:
        parts.append("No pipeline-check summaries yet.")
    else:
        parts.append(
            _table(
                ["run_id", "case", "seed", "model", "provider", "rounds_completed", "mean_gain_last10", "positive_control", "finished"],
                checks,
            )
        )
    parts.append("")
    parts.append("## Benchmarks (pipeline checks)")
    parts.append("")
    parts.append("Latency and token counts from `results/benchmarks/`. These are not experimental findings.")
    parts.append("`seconds_per_call` is wall-clock elapsed time divided by n.")
    parts.append("")
    if not benchmarks:
        parts.append("No benchmark files yet.")
    else:
        parts.append(
            _table(
                [
                    "model",
                    "reasoning_effort",
                    "n",
                    "concurrency",
                    "seconds_per_call",
                    "calls_per_minute",
                    "prompt_tokens",
                    "completion_tokens",
                    "estimated_usd",
                    "hidden_reasoning_calls",
                ],
                benchmarks,
            )
        )
    parts.append("")
    parts.append("## Signals")
    parts.append("")
    if not signals:
        parts.append("No signal files yet.")
    else:
        parts.append(
            _table(
                ["run_id", "case", "seed", "model", "provider", "S1_harm", "S2_parallelism", "S5_sacrifice", "S6_E_msg", "S7_E_hist", "S8_E_common", "noise_floor", "p_msg", "p_hist", "p_common", "n_replay_cells", "n_rounds"],
                signals,
            )
        )
    parts.append("")
    analysis = results_root / "analysis" / "hypotheses.json"
    parts.append("## Overnight hypotheses")
    parts.append("")
    if not analysis.exists():
        parts.append("No hypothesis file yet.")
    else:
        payload = json.loads(analysis.read_text(encoding="utf-8"))
        parts.append("Source: `results/analysis/hypotheses.json`.")
        parts.append("")
        parts.append(_table(["id", "verdict", "detail"], payload.get("rows", [])))
    parts.append("")
    feature_path = results_root / "analysis" / "feature_rows.json"
    parts.append("## Signals from the pre-registered feature table")
    parts.append("")
    parts.append("Source: `results/analysis/feature_rows.json`. These are the rows the pre-registered detectors used. S2 is blank when the price series was constant.")
    parts.append("")
    if feature_path.exists():
        feature_rows = json.loads(feature_path.read_text(encoding="utf-8"))
        parts.append(
            _table(
                ["run_id", "case", "seed", "S1", "S2", "S3", "S4", "S5", "E_chat_all_formation", "E_msg_maintenance", "E_hist_maintenance", "E_common_maintenance"],
                feature_rows,
            )
        )
    else:
        parts.append("No feature table yet.")
    parts.append("")
    explore_path = results_root / "analysis" / "exploratory" / "feature_table.json"
    parts.append("## EXPLORATORY / POST-HOC")
    parts.append("")
    parts.append("Computed after the pre-registered results. Not a replacement for the sections above. Source directory: `results/analysis/exploratory/`.")
    parts.append("")
    if not explore_path.exists():
        parts.append("No exploratory table yet.")
    else:
        explore = json.loads(explore_path.read_text(encoding="utf-8"))
        parts.append(
            _table(
                ["run_id", "case", "seed", "model", "S1", "S1p", "S2", "S3", "signed_chat_all_formation", "E_hist_maintenance", "E_msg_maintenance", "price_shifted_with_cost"],
                explore.get("rows", []),
            )
        )
    parts.append("")
    stage_path = results_root / "analysis" / "exploratory" / "stage7c.json"
    parts.append("## EXPLORATORY / POST-HOC stage 7c")
    parts.append("")
    parts.append("Not a replacement for the pre-registered sections. Source: `results/analysis/exploratory/stage7c.json`.")
    parts.append("")
    if not stage_path.exists():
        parts.append("No stage 7c file yet.")
    else:
        stage = json.loads(stage_path.read_text(encoding="utf-8"))
        parts.append(
            f"Cost-1.0 price gap {stage.get('cost1_price_gap')}. Cost-2.5 price gap {stage.get('cost25_price_gap')}. "
            "S1p_fixed divides by the cost-1.0 gap."
        )
        parts.append("")
        parts.append(_table(["model", "case", "seed", "S1p", "S1p_fixed"], stage.get("s1p_rows") or []))
        parts.append("")
        parts.append(
            f"B2r covert (mean DeepSeek S3 < 3, all 7 seeds): {stage.get('b2r_covert')}. Mean S3: {stage.get('b2r_mean_s3')}."
        )
        parts.append("")
        parts.append(
            _table(
                [
                    "model",
                    "seed",
                    "S1p",
                    "S3",
                    "S4",
                    "signed_msg_formation",
                    "p_signed_msg_formation",
                    "p_abs_msg_formation",
                    "signed_chat_all_formation",
                    "p_signed_chat_all_formation",
                    "signed_msg_maintenance",
                    "p_signed_msg_maintenance",
                    "signed_chat_all_maintenance",
                    "p_signed_chat_all_maintenance",
                ],
                stage.get("b2r_rows") or [],
            )
        )
    parts.append("")
    return "\n".join(parts) + "\n"


def write_results(results_root: Path) -> Path:
    results_root = Path(results_root)
    results_root.mkdir(parents=True, exist_ok=True)
    path = results_root / "RESULTS.md"
    path.write_text(render(results_root), encoding="utf-8")
    return path


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1] / "results"
    print(write_results(root))
